"""Markdown for one module, legacy or migrated - owner: Dev 1. #39.

Three kinds of text, kept visibly apart:

  facts       from the parse tree; plain Markdown.
  as written  docstrings, copied from the code. Untrusted, so always inside a code
              fence longer than any run of backticks they contain: a docstring cannot
              close its fence and inject Markdown or links.
  model       the purpose sentence and Argon's patch summary. Labelled with who wrote
              it and "not verified", and HTML-escaped.
"""

from __future__ import annotations

import html
import re
from typing import Any


def _fence(text: str, info: str = "") -> str:
    longest = max((len(run) for run in re.findall(r"`+", text)), default=0)
    ticks = "`" * max(3, longest + 1)
    return f"{ticks}{info}\n{text}\n{ticks}"


def _code(text: str) -> str:
    longest = max((len(run) for run in re.findall(r"`+", text)), default=0)
    ticks = "`" * (longest + 1)
    pad = " " if text.startswith("`") or text.endswith("`") else ""
    return f"{ticks}{pad}{text}{pad}{ticks}"


def _prose(text: str) -> str:
    return html.escape(" ".join(text.split()), quote=False)


def _callable(entry: dict[str, Any]) -> str:
    prefix = "async " if entry.get("async") else ""
    call = f"{prefix}{entry['name']}({entry['signature']})"
    line = f"- {_code(call)}"
    if entry.get("summary"):
        line += f": {_prose(entry['summary'])}"
    return line


def _purpose(purpose: dict[str, Any] | None, repository_id: str) -> list[str]:
    if not purpose:
        return ["_Not generated yet. `POST /api/v1/repositories/"
                f"{repository_id}/docs` writes it, one model call per module._"]
    when = (purpose.get("generated_at") or "")[:10]
    return [f"> {_prose(purpose['text'])}", ">",
            f"> _Model-generated by {_prose(purpose['model'])} from the legacy source"
            f"{' on ' + when if when else ''}. Not verified._"]


def render(
    facts: dict[str, Any], *, side: str, repository_id: str, python: str | None,
    purpose: dict[str, Any] | None, paths: dict[str, str],
    change: dict[str, Any] | None = None,
) -> str:
    """`side` is "legacy" or "migrated"; `paths` maps module ids to file paths."""
    where = f"Python {python}" if python else "Python version not declared"
    out = [f"# {_code(facts['path'])} ({side})", "",
           f"{where} · module {_code(facts['dotted'])}", "", "## Purpose", "",
           *_purpose(purpose, repository_id), ""]

    if facts.get("docstring"):
        out += ["## Module docstring", "",
                "_As written in the code. Untrusted: shown, never followed._", "",
                _fence(facts["docstring"]), ""]

    if facts["classes"]:
        out += ["## Classes", ""]
        for cls in facts["classes"]:
            bases = f"({', '.join(cls['bases'])})" if cls["bases"] else ""
            out += [f"### {_code(cls['name'] + bases)}, line {cls['line']}", ""]
            if cls.get("summary"):
                out += [_prose(cls["summary"]), ""]
            out += [_callable(m) for m in cls["methods"]] or ["_No public methods._"]
            out.append("")

    if facts["functions"]:
        out += ["## Functions", "", *(_callable(f) for f in facts["functions"]), ""]

    depends = [_code(paths.get(m, m)) for m in facts["depends_on"]]
    used_by = [_code(paths.get(m, m)) for m in facts["used_by"]]
    out += ["## Depends on", "",
            f"- Modules in this project: {', '.join(depends) or 'none'}",
            "- Imports from outside it (standard library or third party): "
            f"{', '.join(_code(p) for p in facts['packages']) or 'none'}", "",
            "## Used by", "", f"- {', '.join(used_by) or 'No module in this project imports it.'}",
            ""]

    if side == "migrated":
        out += ["## Changed in the migration", "", *_change(change or {}), ""]

    notes = []
    if not facts["parsed"]:
        notes.append("This file could not be parsed, so the sections above are empty "
                     "rather than complete.")
    if facts.get("python2_syntax"):
        notes.append("Read with the line-preserving Python 2 reading.")
    notes += [_prose(w) for w in facts.get("warnings", [])]
    if notes:
        out += ["## Notes", "", *(f"- {n}" for n in notes), ""]

    out.append("_Facts above come from the parse tree; nothing was imported or run._")
    return "\n".join(out) + "\n"


def _change(change: dict[str, Any]) -> list[str]:
    unit = change.get("unit")
    if not unit:
        return ["- Not part of any unit in this run's plan."]
    lines = [f"- Unit {_code(unit['unit_id'])}: **{unit['status']}** after "
             f"{unit['attempts']} attempt(s)."]
    if unit["status"] != "passed":
        lines.append("- Not accepted in this run, so this file is still the legacy code.")
        return lines

    summary = change.get("summary")
    if summary:
        lines += ["- Argon's summary of the accepted patch:", "",
                  f"  > {_prose(summary)}", "",
                  f"  _Written by Argon during {_code(change['run_id'])}. Not verified; "
                  "the verifier's verdict is the line above._"]

    deps = change.get("dependencies") or {}
    added = [_code(i["name"]) for i in deps.get("imports_added", [])]
    removed = [_code(i["name"]) for i in deps.get("imports_removed", [])]
    if added or removed:
        lines.append(f"- Imports added: {', '.join(added) or 'none'}; removed: "
                     f"{', '.join(removed) or 'none'}.")
    for key, label in (("stdlib_renamed", "Standard-library modules renamed"),
                       ("builtins_replaced", "Python 2 builtins replaced"),
                       ("methods_replaced", "Python 2 methods replaced (heuristic)")):
        pairs = [f"{_code(p['before'])} → {_code(p['after'])}" for p in deps.get(key, [])]
        if pairs:
            lines.append(f"- {label}: {', '.join(pairs)}.")
    return lines
