@pytest.fixture
def atlas(monkeypatch):
    saved = {"purposes": {}, "status": {}, "indexed": {}}

    async def cached_purposes(repo_id):
        return {k[1:]: v for k, v in saved["purposes"].items() if k[0] == repo_id}

    async def save_purpose(document):
        key = (document["repository_id"], document["path"], document["source_hash"])
        saved["purposes"][key] = dict(document)

    async def module_descriptions(repo_id):
        return dict(saved["indexed"])

    async def get_generation(repo_id):
        return saved["status"].get(repo_id)

    async def set_generation(repo_id, **fields):
        saved["status"].setdefault(repo_id, {}).update(fields)

    for name, fn in [("cached_purposes", cached_purposes), ("save_purpose", save_purpose),
                     ("module_descriptions", module_descriptions),
                     ("get_generation", get_generation), ("set_generation", set_generation)]:
        monkeypatch.setattr(store, name, fn)
    return saved


