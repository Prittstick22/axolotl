async def test_a_run_documents_both_sides_with_the_accepted_change(run_world):
    result = await docs.run_docs("run_x")

    assert result["revision"] == "rev_2"
    game = next(m for m in result["modules"] if m["path"] == "pkg/game.py")
    change = game["migrated"]["change"]
    assert change["unit"] == {"unit_id": "unit_game", "status": "passed", "attempts": 2}
    assert change["summary"] == "Replace raw_input with input"  # the accepted patch
    assert [b["before"] for b in change["dependencies"]["builtins_replaced"]] == ["raw_input"]
    markdown = game["migrated"]["markdown"]
    assert "## Changed in the migration" in markdown
    assert "Written by Argon during `run_x`. Not verified" in markdown

    board = next(m for m in result["modules"] if m["path"] == "pkg/board.py")
    assert board["migrated"]["change"]["summary"] is None
    assert "still the legacy code" in board["migrated"]["markdown"]


