async def test_changed_source_is_not_given_an_old_purpose(tmp_path, atlas, model):
    analyses, _ = analyse(write(tmp_path / "v1", LEGACY))
    await prose.generate("repo_x", prose.candidates(analyses), "gemini-3.8-flash")

