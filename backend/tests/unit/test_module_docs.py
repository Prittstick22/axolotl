async def test_one_call_per_non_test_module_and_never_twice(tmp_path, atlas, model):
    analyses, _ = analyse(write(tmp_path, LEGACY))
    todo = prose.candidates(analyses)

    await prose.generate("repo_x", todo, "gemini-3.8-flash")
    assert sorted(model["paths"]) == ["pkg/__init__.py", "pkg/board.py", "pkg/game.py"]
    assert "tests/test_game.py" not in model["paths"]  # visible case inputs stay out
    assert atlas["status"]["repo_x"]["state"] == prose.READY

    model["paths"].clear()
    await prose.generate("repo_x", todo, "gemini-3.8-flash")
    assert model["paths"] == []  # cached by source hash
    found = await prose.purposes("repo_x", analyses)
    assert found["pkg/game.py"]["text"] == "Describes pkg/game.py."
    assert found["pkg/game.py"]["basis"] == "model_generated"


