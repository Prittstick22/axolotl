def test_a_generation_left_running_by_a_stopped_backend_goes_stale():
    now = datetime.now(UTC)
    assert prose.is_active({"state": "generating", "started_at": now})
    assert not prose.is_active({"state": "generating",
                                "started_at": now - timedelta(minutes=16)})
    assert not prose.is_active({"state": "ready", "started_at": now})


