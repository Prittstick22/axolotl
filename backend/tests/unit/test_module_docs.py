def test_an_untrusted_docstring_cannot_close_its_fence(tmp_path):
    analyses, edges = analyse(write(tmp_path, LEGACY))
    facts = module_facts(analyses["module_pkg__game"], edges)
    text = render(facts, side="legacy", repository_id="repo_x", python="2.7",
                         purpose=None, paths={})

    fenced = text.split("## Module docstring", 1)[1]
    assert "\n````\nPlays games." in fenced  # four backticks: longer than the ``` inside
    assert "Untrusted: shown, never followed" in fenced
    assert "Not generated yet" in text


def test_model_prose_is_labelled_and_escaped(tmp_path):
    analyses, edges = analyse(write(tmp_path, LEGACY))
    facts = module_facts(analyses["module_pkg__game"], edges)
    purpose = {"text": "Runs <script>the</script> game loop.", "model": "gemini-3.8-flash",
               "origin": "generated", "generated_at": "2026-10-24T20:00:00+00:00",
               "basis": "model_generated"}
    text = render(facts, side="legacy", repository_id="repo_x", python="2.7",
                         purpose=purpose, paths={})
    assert "&lt;script&gt;" in text and "<script>" not in text
    assert "Model-generated by gemini-3.8-flash from the legacy source on 2026-10-24" in text
    assert "Not verified" in text


