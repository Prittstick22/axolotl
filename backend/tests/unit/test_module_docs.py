def test_facts_are_the_public_surface_and_the_imports_both_ways(tmp_path):
    analyses, edges = analyse(write(tmp_path, LEGACY))
    game = module_facts(analyses["module_pkg__game"], edges)

    assert [c["name"] for c in game["classes"]] == ["Game"]
    assert game["classes"][0]["bases"] == ["object"]
    assert [m["name"] for m in game["classes"][0]["methods"]] == ["__init__", "play"]
    assert game["classes"][0]["methods"][1]["signature"] == "self, move=None"
    assert [f["name"] for f in game["functions"]] == ["start"]  # _hidden is private
    assert "module_pkg__board" in game["depends_on"]
    assert "os" in game["packages"]
    assert {"module_pkg", "module_tests__test_game"} <= set(game["used_by"])
    assert game["basis"] == "static_ast"


def test_a_python2_module_still_gives_its_facts(tmp_path):
    write(tmp_path, {"old.py": 'class Old:\n    def run(self):\n        print "hi"\n'})
    analyses, edges = analyse(tmp_path)
    facts = module_facts(analyses["module_old"], edges)
    assert facts["python2_syntax"] is True
    assert [m["name"] for m in facts["classes"][0]["methods"]] == ["run"]


